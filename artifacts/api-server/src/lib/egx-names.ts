/** Resolve a free-form company name to an EGX symbol, or null when nothing
 *  matches. Prefers an exact alias, then the longest alias contained in the
 *  question (so «سهم مدينة مصر» → MASR beats «مدينة نصر»). */
export function resolveEgxAlias(query: string): string | null {
  const q = String(query || "")
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[\u064B-\u065F\u0670\u0640]/g, "")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ي")
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
  if (!q) return null;
  const exact = EGX_ALIASES[q];
  if (exact) return exact;
  let best: string | null = null;
  let bestLen = 0;
  for (const [key, sym] of Object.entries(EGX_ALIASES)) {
    if (key.length <= bestLen) continue;
    if (q.includes(key)) {
      best = sym;
      bestLen = key.length;
    }
  }
  return best;
}
